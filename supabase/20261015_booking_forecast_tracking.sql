-- Store daily forecast snapshots so actual completed months can be compared
-- with the most recent one-month-ahead prediction.

create table if not exists public.booking_forecast_snapshots (
	id bigint generated by default as identity primary key,
	forecast_date date not null,
	target_month date not null,
	predicted_bookings integer not null check (predicted_bookings >= 0),
	forecast_source text not null check (forecast_source in ('ai', 'historical')),
	reason text not null default '',
	actual_bookings integer check (actual_bookings is null or actual_bookings >= 0),
	actual_updated_at timestamptz,
	created_at timestamptz not null default now(),
	constraint booking_forecast_snapshots_target_month_start
		check (extract(day from target_month) = 1),
	constraint booking_forecast_snapshots_precedes_target
		check (forecast_date < target_month),
	constraint booking_forecast_snapshots_day_target_key
		unique (forecast_date, target_month)
);

create index if not exists booking_forecast_snapshots_target_month_idx
	on public.booking_forecast_snapshots (target_month desc, forecast_date desc);

alter table public.booking_forecast_snapshots enable row level security;
revoke all on table public.booking_forecast_snapshots from public, anon, authenticated;
grant select, insert, update on table public.booking_forecast_snapshots to service_role;
grant usage, select on sequence public.booking_forecast_snapshots_id_seq to service_role;
